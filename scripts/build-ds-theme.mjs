// Generates src/ds-theme.css: a Tailwind theme that exposes the design
// system's tokens as utility classes. Run `npm run build:ds-theme` after
// upgrading @pikonen/second-design-system.
//
// The design system ships its tokens as plain CSS custom properties, not as a
// Tailwind theme, so on their own they produce no classes at all. Every entry
// here only POINTS at the package's variable — no value is copied — so the
// package stays the single source of truth and its generated-from-Figma files
// are never restated in this repo.
//
//   package variable      utility                 example
//   --color-slate-500     text-/bg-/border-…      text-slate-500
//   --space-48            gap-/p-/m-/w-…          gap-48 (48px)
//   --radius-md           rounded-…               rounded-md
//
// Tailwind's own defaults for those three namespaces are cleared first, so
// only token values exist: gap-48 is the 48px token, never Tailwind's 12rem,
// and an off-scale number such as gap-5 simply produces no class.

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const tokens = JSON.parse(
  readFileSync(require.resolve("@pikonen/second-design-system/tokens/tokens.json"), "utf8"),
);

const lines = [
  "/* Generated by scripts/build-ds-theme.mjs from",
  "   @pikonen/second-design-system/tokens/tokens.json. Do not edit by hand. */",
  "@theme inline {",
  "  --color-*: initial;",
  "  --spacing: initial;",
  "  --spacing-*: initial;",
  "  --radius-*: initial;",
  "",
  ...Object.keys(tokens.color).map((name) => `  --color-${name}: var(--color-${name});`),
  "",
  ...Object.keys(tokens.space).map((name) => `  --spacing-${name}: var(--space-${name});`),
  "",
  ...Object.keys(tokens.radius).map((name) => `  --radius-${name}: var(--radius-${name});`),
  "",
  "  --font-sans: var(--font-sans);",
  "  --font-serif: var(--font-serif);",
  "}",
  "",
];

writeFileSync(new URL("../src/ds-theme.css", import.meta.url), lines.join("\n"));
